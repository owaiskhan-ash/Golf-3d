export type ClubCategory = 'wood' | 'hybrid' | 'iron' | 'wedge' | 'putter';

export interface ClubSpec {
  id: string;
  name: string;
  shortName: string;
  category: ClubCategory;
  loftDeg: number;           // Static loft at center of face
  lieDeg: number;            // Standard lie angle
  shaftLengthInches: number; // Club length in inches
  headMassGrams: number;     // Clubhead mass (g)
  cor: number;               // Coefficient of restitution of face (USGA max 0.83)
  gearRadiusInches: number;  // Horizontal bulge radius (inches; high for woods, flat for irons)
  rollRadiusInches: number;  // Vertical roll radius (inches)
  tourClubSpeedMph: number;  // PGA Tour TrackMan average clubhead speed
  tourAttackAngleDeg: number;// Typical Tour attack angle (+ up, - down)
  tourDynamicLoftDeg: number;// Typical Tour dynamic loft at impact (accounts for shaft lean)
  expectedCarryYds: number;  // TrackMan Tour baseline carry (for caddie recommendations)
  spinFactorScale: number;   // Groove/spin calibration multiplier
}

